package com.tecnocampus.LS2.protube_back.services;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.tecnocampus.LS2.protube_back.domain.Video;
import com.tecnocampus.LS2.protube_back.repository.VideoRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.dao.DataAccessException;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.stream.Stream;

/**
 * Imports into the database the videos found in the video store generated by {@code tooling/videoGrabber}.
 * Each video is a {@code <id>.json} file next to its {@code <id>.mp4} and {@code <id>.webp} (thumbnail).
 */
@Service
public class VideoStoreImporter {

    private static final Logger LOG = LoggerFactory.getLogger(VideoStoreImporter.class);

    private final VideoRepository videoRepository;
    private final ObjectMapper objectMapper;

    public VideoStoreImporter(VideoRepository videoRepository, ObjectMapper objectMapper) {
        this.videoRepository = videoRepository;
        this.objectMapper = objectMapper;
    }

    /**
     * Imports every valid video of the store that is not in the database yet, so it can run on every startup.
     * Invalid or incomplete videos are logged and skipped.
     *
     * @return the number of videos imported
     */
    public int importFrom(Path storeDir) {
        if (!Files.isDirectory(storeDir)) {
            LOG.warn("Video store {} is not a directory: no videos imported", storeDir);
            return 0;
        }

        List<Path> jsonFiles;
        try (Stream<Path> files = Files.list(storeDir)) {
            jsonFiles = files.filter(file -> file.getFileName().toString().endsWith(".json")).sorted().toList();
        } catch (IOException e) {
            LOG.error("Could not read the video store {}", storeDir, e);
            return 0;
        }

        int imported = 0;
        for (Path jsonFile : jsonFiles) {
            if (importVideo(storeDir, jsonFile)) {
                imported++;
            }
        }
        LOG.info("Imported {} new videos from {}", imported, storeDir);
        return imported;
    }

    private boolean importVideo(Path storeDir, Path jsonFile) {
        StoreVideo json;
        try {
            json = objectMapper.readValue(jsonFile.toFile(), StoreVideo.class);
        } catch (IOException e) {
            LOG.warn("Skipping {}: invalid json ({})", jsonFile.getFileName(), e.getMessage());
            return false;
        }

        if (isBlank(json.id()) || isBlank(json.title()) || json.timestamp() == null) {
            LOG.warn("Skipping {}: id, title and timestamp are required", jsonFile.getFileName());
            return false;
        }
        if (videoRepository.existsByStoreId(json.id())) {
            return false;
        }

        String videoFile = json.id() + ".mp4";
        String thumbnailFile = json.id() + ".webp";
        if (!Files.isRegularFile(storeDir.resolve(videoFile)) || !Files.isRegularFile(storeDir.resolve(thumbnailFile))) {
            LOG.warn("Skipping {}: {} or {} is missing", jsonFile.getFileName(), videoFile, thumbnailFile);
            return false;
        }

        try {
            videoRepository.save(toVideo(json, videoFile, thumbnailFile));
            return true;
        } catch (DataAccessException e) {
            LOG.warn("Skipping {}: could not be saved ({})", jsonFile.getFileName(), e.getMessage());
            return false;
        }
    }

    private static Video toVideo(StoreVideo json, String videoFile, String thumbnailFile) {
        String description = json.meta() == null ? null : json.meta().description();
        int durationSeconds = json.duration() == null ? 0 : (int) Math.round(json.duration());
        return new Video(json.id(), json.title(), description, json.user(), durationSeconds,
                json.width(), json.height(), Instant.ofEpochSecond(json.timestamp()), videoFile, thumbnailFile);
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }

    /**
     * Fields of the store json used by this story; the rest (tags, categories, comments...) are ignored.
     */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record StoreVideo(String id, Integer width, Integer height, Double duration, String title, String user,
                      Long timestamp, Meta meta) {
    }

    @JsonIgnoreProperties(ignoreUnknown = true)
    record Meta(String description) {
    }
}
